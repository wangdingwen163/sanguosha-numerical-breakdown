# -*- coding: utf-8 -*-
"""
三国杀 · 关键牌概率与期望收益计算（纯数学推导，可重跑）

运行：python scripts/calc_probability.py
输出：data/probability_results.json  + 控制台可读报告

口径说明（重要）
----------------
* 牌堆 = 标准版108（含4张EX）+ 军争篇52 = 160 张（中国内地桌游版本，见 deck_data.py）
* 起手 = 4 张（见底表「开局规则」条，标注来源）
* 所有抽牌概率 = 超几何分布 P(X≥1) = 1 - C(N-K, n) / C(N, n)
  N=160（牌堆），K=该类牌张数，n=抽取张数
* 「期望命中伤害」= 1 - P(防守方手牌中存在【闪】)，假设防守方手牌为随机 m 张
  —— 这是**下界模型**：真实牌局中玩家会主动留【闪】，实际命中率更低
* 「单卡期望收益」使用**作者自建参数模型**，把「1点体力」折算为 k 张牌，
  k 是唯一自由参数，结果以 k ∈ {1, 1.5, 2} 的形式给出区间，不预设结论
"""
import json
import math
import os
from math import comb

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data")

N_DECK = 160          # 牌堆总张数
HAND_START = 4        # 起手张数
DRAW_PER_TURN = 2     # 每回合摸牌阶段摸牌数


# --------------------------------------------------------------------------
# 核心概率工具
# --------------------------------------------------------------------------
def p_at_least_one(K, n, N=N_DECK):
    """从 N 张牌堆中抽 n 张，至少抽到 1 张「共 K 张的那类牌」的概率。"""
    if K <= 0 or n <= 0:
        return 0.0
    if N - K < n:
        return 1.0
    return 1.0 - comb(N - K, n) / comb(N, n)


def p_none(K, n, N=N_DECK):
    return 1.0 - p_at_least_one(K, n, N)


def e_count(K, n, N=N_DECK):
    """n 张牌中该类牌的期望张数（超几何期望 = n*K/N）。"""
    return n * K / N


# --------------------------------------------------------------------------
# 牌堆张数（与 deck_data.py 一致，这里显式抄一份便于脚本独立重跑）
# --------------------------------------------------------------------------
COUNTS = {
    "杀": 30, "火杀": 5, "雷杀": 9,
    "闪": 24, "桃": 12, "酒": 5,
    "无懈可击": 7, "借刀杀人": 2, "过河拆桥": 6, "顺手牵羊": 5,
    "无中生有": 4, "决斗": 3, "南蛮入侵": 3, "万箭齐发": 1,
    "桃园结义": 1, "五谷丰登": 2, "乐不思蜀": 3, "闪电": 2,
    "铁索连环": 6, "火攻": 3, "兵粮寸断": 2,
}
COUNTS["杀系(含属性杀)"] = COUNTS["杀"] + COUNTS["火杀"] + COUNTS["雷杀"]  # 44
COUNTS["武器"] = 2 + 10     # 诸葛连弩×2 + 其余10把各1
COUNTS["防具"] = 2 + 1 + 2 + 1   # 八卦阵2 仁王盾1 藤甲2 白银狮子1
COUNTS["+1坐骑"] = 4        # 的卢/绝影/爪黄飞电/骅骝
COUNTS["-1坐骑"] = 3        # 赤兔/大宛/紫骍
COUNTS["坐骑合计"] = COUNTS["+1坐骑"] + COUNTS["-1坐骑"]
COUNTS["装备合计"] = COUNTS["武器"] + COUNTS["防具"] + COUNTS["坐骑合计"]

KEY_ORDER = ["杀系(含属性杀)", "杀", "火杀", "雷杀", "闪", "桃", "酒",
             "无懈可击", "借刀杀人", "过河拆桥", "顺手牵羊", "无中生有",
             "决斗", "南蛮入侵", "万箭齐发", "桃园结义", "五谷丰登",
             "乐不思蜀", "闪电", "铁索连环", "火攻", "兵粮寸断",
             "武器", "防具", "坐骑合计"]


# --------------------------------------------------------------------------
# 1. 起手 / 累计摸牌概率
# --------------------------------------------------------------------------
def hand_probabilities():
    rows = []
    for name in KEY_ORDER:
        K = COUNTS[name]
        rows.append({
            "牌名": name,
            "张数": K,
            "占比%": round(K / N_DECK * 100, 3),
            "起手4张至少1张%": round(p_at_least_one(K, 4) * 100, 2),
            "首轮6张至少1张%": round(p_at_least_one(K, 6) * 100, 2),
            "第3回合10张至少1张%": round(p_at_least_one(K, 10) * 100, 2),
            "起手4张期望张数": round(e_count(K, 4), 4),
        })
    return rows


# --------------------------------------------------------------------------
# 2. 期望命中伤害（【杀】的命中模型）
# --------------------------------------------------------------------------
def hit_model():
    """防守方手牌 m 张时，【杀】的期望伤害 = 1 - P(手牌含【闪】)。"""
    rows = []
    for m in range(1, 13):
        p_shan = p_at_least_one(COUNTS["闪"], m)
        rows.append({
            "防守方手牌数": m,
            "P(手中有闪)%": round(p_shan * 100, 2),
            "期望伤害/张杀": round(1 - p_shan, 4),
            "命中即被闪概率%": round(p_shan * 100, 2),
        })
    return rows


def hit_model_with_armor():
    """叠加【八卦阵】：判定红色(牌堆红桃+方块=80张/160)则为闪，等效额外1次50%闪避。"""
    red = 80  # 红桃26(标准13×2)+方块26 + 军争红桃13+方块13 = 80
    p_bagua = red / N_DECK
    rows = []
    for m in range(1, 9):
        p_shan = p_at_least_one(COUNTS["闪"], m)
        # 需要闪时：先手牌闪，否则八卦判定成功
        p_avoid = p_shan + (1 - p_shan) * p_bagua
        rows.append({
            "防守方手牌数": m,
            "P(手牌有闪)%": round(p_shan * 100, 2),
            "叠加八卦阵后免伤概率%": round(p_avoid * 100, 2),
            "期望伤害(带八卦阵)": round(1 - p_avoid, 4),
        })
    return {"八卦阵红色判定率": round(p_bagua, 4), "结果": rows}


# --------------------------------------------------------------------------
# 3. 单卡期望收益（作者自建参数模型）
# --------------------------------------------------------------------------
def card_ev(k_values=(1.0, 1.5, 2.0)):
    """
    模型定义（单位：张牌；k = 1 点体力折算成的牌数）
    - 【杀】  成本1；收益 = p_hit * k          p_hit = 1 - P(对手m张手牌含闪)
    - 【闪】  成本1；收益 = k                （抵消1点伤害）
    - 【桃】  成本1；收益 = k                （回复1点体力）
    - 【酒】  成本1；收益 = k                （当回合杀伤害基数+1，需有杀兑付）
    - 【无懈可击】成本1；收益 = k*0.7        （抵消1张锦囊；锦囊期望收益取0.7k，
                                              —— 该系数为模型假设，见底表）
    - 【无中生有】成本1；收益 = 2 张牌        （纯牌差，与k无关）
    - 【顺手牵羊】成本1；收益 = 2 张牌        （获得对方1张，相对牌差+1，含1张牌的净增）
    - 【过河拆桥】成本1；收益 = 1.4 张牌      （不获得牌，估值=被拆牌的平均价值+节奏）
    - 【借刀杀人】成本1；收益 = P(目标未出杀)*W_武器 + P(目标出杀)*内耗值
    """
    out = {"参数说明": "k = 1点体力折算的牌数；W_武器 = 武器牌估值(张)；内耗值 = 逼对手消耗1张杀的价值(张)",
           "按k取值的结果": {}}
    for k in k_values:
        # 对手4张手牌时的命中率
        p_has_shan = p_at_least_one(COUNTS["闪"], 4)
        p_hit = 1 - p_has_shan
        # 借刀杀人：目标4张手牌无【杀】的概率
        p_no_sha = p_none(COUNTS["杀系(含属性杀)"], 4)
        W_weapon = 1.0 + 0.5 * k      # 武器 = 1张牌 + 攻击范围估值(取0.5k)
        neihao = 0.5                  # 逼对手消耗1张杀的价值
        rows = [
            {"牌": "杀", "公式": "p_hit*k - 1", "净收益(张)": round(p_hit * k - 1, 3),
             "关键中间量": f"p_hit={p_hit:.3f}"},
            {"牌": "闪", "公式": "k - 1", "净收益(张)": round(k - 1, 3), "关键中间量": "被动使用"},
            {"牌": "桃", "公式": "k - 1", "净收益(张)": round(k - 1, 3), "关键中间量": "可救援队友"},
            {"牌": "酒", "公式": "k - 1", "净收益(张)": round(k - 1, 3), "关键中间量": "需回合内有杀兑付"},
            {"牌": "无懈可击", "公式": "0.7k - 1", "净收益(张)": round(0.7 * k - 1, 3),
             "关键中间量": "系数0.7为模型假设"},
            {"牌": "无中生有", "公式": "2 - 1 = +1", "净收益(张)": 1.0, "关键中间量": "与k无关"},
            {"牌": "顺手牵羊", "公式": "+1(相对牌差)", "净收益(张)": 1.0, "关键中间量": "需距离1"},
            {"牌": "过河拆桥", "公式": "1.4 - 1 = +0.4", "净收益(张)": 0.4, "关键中间量": "估值假设"},
            {"牌": "借刀杀人", "公式": "p_no_sha*W + (1-p_no_sha)*内耗 - 1",
             "净收益(张)": round(p_no_sha * W_weapon + (1 - p_no_sha) * neihao - 1, 3),
             "关键中间量": f"p_no_sha={p_no_sha:.3f}, W={W_weapon:.2f}"},
        ]
        out["按k取值的结果"][f"k={k}"] = rows
    return out


# --------------------------------------------------------------------------
# 4. 全场/每回合产出（8人身份局）
# --------------------------------------------------------------------------
def table_output(players=8):
    total_per_round = players * DRAW_PER_TURN      # 每轮全场摸牌总量
    rows = []
    for name in ["杀系(含属性杀)", "闪", "桃", "酒", "无懈可击", "借刀杀人",
                 "过河拆桥", "顺手牵羊", "无中生有", "决斗", "南蛮入侵",
                 "万箭齐发", "桃园结义", "五谷丰登", "武器", "防具", "坐骑合计"]:
        K = COUNTS[name]
        rows.append({
            "牌名": name, "张数": K,
            "每轮期望出现张数": round(e_count(K, total_per_round), 3),
            "平均每几轮出现1张": round(1 / e_count(K, total_per_round), 2),
        })
    return {"每轮全场摸牌量": total_per_round, "结果": rows}


# --------------------------------------------------------------------------
# 5. 距离与攻击范围覆盖（官方规则集《数值·距离/攻击范围》）
# --------------------------------------------------------------------------
def distance_coverage(players=8):
    # 8人围坐：与自己距离为 1,1,2,2,3,3,4 的座位各若干
    seat_dist = []
    for i in range(1, players):
        d = min(i, players - i)
        seat_dist.append(d)
    seat_dist.sort()
    total = len(seat_dist)
    rows = []
    for r in range(1, 7):
        covered = sum(1 for d in seat_dist if d <= r)
        rows.append({
            "攻击范围": r,
            "可及座位数(共7个)": covered,
            "覆盖全场比例%": round(covered / total * 100, 1),
        })
    return {
        "最近若干距离的座位数分布": {d: seat_dist.count(d) for d in sorted(set(seat_dist))},
        "平均距离": round(sum(seat_dist) / total, 3),
        "覆盖表": rows,
        "说明": "距离定义见官方规则集3.0《用语·数值·距离》：逆/顺时针最短路径上的箭头数；自己与自己距离为0；最短为1。",
    }


# --------------------------------------------------------------------------
# 6. 平衡旋钮敏感性（「拧一下」会怎样）
# --------------------------------------------------------------------------
def knobs():
    base = {
        "起手4张含闪概率%": round(p_at_least_one(24, 4) * 100, 2),
        "起手4张含杀概率%": round(p_at_least_one(44, 4) * 100, 2),
        "起手4张含桃概率%": round(p_at_least_one(12, 4) * 100, 2),
        "对手4张手牌时的期望命中伤害": round(1 - p_at_least_one(24, 4), 4),
    }
    experiments = []

    def sim(label, shan=None, sha=None, tao=None, note=""):
        s = shan if shan is not None else 24
        a = sha if sha is not None else 44
        t = tao if tao is not None else 12
        experiments.append({
            "旋钮": label,
            "闪张数": s, "杀系张数": a, "桃张数": t,
            "起手4张含闪%": round(p_at_least_one(s, 4) * 100, 2),
            "起手4张含杀%": round(p_at_least_one(a, 4) * 100, 2),
            "起手4张含桃%": round(p_at_least_one(t, 4) * 100, 2),
            "期望命中伤害": round(1 - p_at_least_one(s, 4), 4),
            "备注": note,
        })

    sim("基准（标准+军争，160张）", note="底表基准")
    sim("旋钮A：闪 +6（24→30）", shan=30, note="防御牌增发")
    sim("旋钮B：闪 -6（24→18）", shan=18, note="攻击环境")
    sim("旋钮C：桃 12→16", tao=16, note="生存能力增发")
    sim("旋钮D：杀系 44→36（去属性杀）", sha=36, note="回到接近标准版浓度")
    return {"基准": base, "实验": experiments}


