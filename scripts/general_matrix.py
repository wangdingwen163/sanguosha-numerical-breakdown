def build():
    table = []
    for name, clauses in ENCODE.items():
        score = {"输出": 0, "防御": 0, "控制": 0, "支援": 0}
        for _, _, dim in clauses:
            score[{"OUT": "输出", "DEF": "防御", "CTL": "控制", "SUP": "支援"}[dim]] += 1
        table.append({
            "武将": name,
            "技能条数": len(clauses),
            "输出": score["输出"],
            "防御": score["防御"],
            "控制": score["控制"],
            "支援": score["支援"],
            "归类型": max(score, key=score.get) if max(score.values()) > 0 else "无",
            "技能清单": [f"{s}：{t}" for s, t, _ in clauses],
        })
    # 按"动作总数"排序，便于阅读
    table.sort(key=lambda r: (-(r["输出"] + r["防御"] + r["控制"] + r["支援"]), r["武将"]))
    return table


